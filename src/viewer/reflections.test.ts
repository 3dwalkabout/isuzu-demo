import assert from "node:assert/strict";
import { test } from "node:test";
import { BoxGeometry, Group, Mesh, MeshPhysicalMaterial, MeshStandardMaterial, ShaderLib, type WebGLRenderer } from "three";
import { createReflections } from "./reflections.ts";

test("reflection changes share one reversible fade without changing diffuse light, paint finish or shadows", () => {
  const root = new Group();
  const paint = new MeshPhysicalMaterial({ metalness: 0.55, roughness: 0.32, clearcoat: 1 });
  const floor = new MeshStandardMaterial({ envMapIntensity: 0.18 });
  const geometry = new BoxGeometry();
  const car = new Mesh(geometry, paint); car.castShadow = true;
  root.add(car, new Mesh(geometry, floor));
  const reflections = createReflections();
  reflections.attach(root);
  const compile = paint.onBeforeCompile;
  reflections.attach(root);
  assert.equal(paint.onBeforeCompile, compile, "shared materials must only be patched once");
  const shader = { uniforms: {}, fragmentShader: ShaderLib.physical.fragmentShader } as Parameters<typeof paint.onBeforeCompile>[0];
  paint.onBeforeCompile(shader, {} as WebGLRenderer);
  const floorShader = { uniforms: {}, fragmentShader: ShaderLib.standard.fragmentShader } as Parameters<typeof floor.onBeforeCompile>[0];
  floor.onBeforeCompile(floorShader, {} as WebGLRenderer);
  assert.equal(shader.uniforms.environmentReflections, floorShader.uniforms.environmentReflections);
  assert.ok(shader.fragmentShader.includes("#include <lights_fragment_maps>"), "diffuse environment lighting must remain intact");
  assert.ok(shader.fragmentShader.includes("radiance *= environmentReflections"));
  assert.ok(shader.fragmentShader.includes("clearcoatRadiance *= environmentReflections"));
  reflections.set(false, 0);
  reflections.update(150);
  assert.equal(shader.uniforms.environmentReflections.value, 0.5);
  reflections.set(true, 150);
  reflections.update(300);
  assert.equal(shader.uniforms.environmentReflections.value, 0.75, "reversal must start from the current strength");
  reflections.set(false, 300, true);
  assert.equal(shader.uniforms.environmentReflections.value, 0);
  assert.equal(paint.metalness, 0.55);
  assert.equal(paint.roughness, 0.32);
  assert.equal(paint.clearcoat, 1);
  assert.equal(floor.envMapIntensity, 0.18);
  assert.equal(car.castShadow, true);
  reflections.set(true, 400, true);
  assert.equal(shader.uniforms.environmentReflections.value, 1);
  geometry.dispose(); paint.dispose(); floor.dispose();
});
